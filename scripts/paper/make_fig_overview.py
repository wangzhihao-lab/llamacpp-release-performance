#!/usr/bin/env python3
"""Generate the study-overview figure of the paper (Figure 2 in the manuscript).

A flow diagram: the llama.cpp repository as a cylinder, the six numbered steps as rounded boxes
with short labels, the data each step produces as a document stack with its count, and labelled
connectors where a step works on each item of the previous result.  A small tag names the research
question that each result answers.

The counts are read from the macros of ``paper/numbers.tex`` (generated by
``scripts/paper/make_numbers.py``), so the figure stays in step with the text.  Nothing under
``paper/`` other than ``paper/figs/`` is written.

Outputs: ``paper/figs/overview.pdf`` and ``paper/figs/overview.svg`` (editable SVG text), 13.7 cm wide.

Run: taskpolicy -b nice -n 19 uv run --no-project --with pandas --with numpy --with matplotlib python3 -I scripts/paper/make_fig_overview.py
"""

from __future__ import annotations

import logging
import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import glyphs as gl
import matplotlib.pyplot as plt
from figstyle import FULL_WIDTH_CM, INDIGO, LIGHT_BLUE, apply_style, cm, save_figure
from matplotlib.patches import FancyBboxPatch

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[2]

HEIGHT_CM = 4.72
LABEL_PT = 7.0
LINK_PT = 6.5
STEP_H = 0.92  # height of a step box
DOC_H = 1.0  # height of the front page of a document stack
DOC_DX, DOC_DY = 0.09, 0.08  # shift of each page behind the front page
ROW_Y = (4.05, 2.27, 0.6)  # vertical centres of the three rows
GAP = 0.86  # horizontal gap between neighbours in a row (arrow length)

_MACRO_RE = re.compile(r"\\newcommand\{\\([A-Za-z]+)\}\{([^{}]*)\}")


def read_macros(path: Path) -> dict[str, str]:
    """Parse ``\\newcommand{\\name}{value}`` lines of ``numbers.tex``.

    Args:
        path: Path to ``paper/numbers.tex``.

    Returns:
        Mapping from macro name (without backslash) to its value.

    Raises:
        FileNotFoundError: If the file is missing.
    """
    return dict(_MACRO_RE.findall(path.read_text(encoding="utf-8")))


@dataclass(frozen=True)
class Node:
    """One element of the flow: the repository, a step or a data set."""

    kind: str  # "repo", "step" or "data"
    text: str
    width: float
    rq: str = ""  # research question answered by this data set


def build_nodes(m: dict[str, str]) -> dict[str, Node]:
    """The repository, the six steps and the data each step produces, with counts from the macros.

    Args:
        m: Macros from ``numbers.tex``.

    Returns:
        Nodes by key (``repo``, ``s1``..``s6``, ``d1``..``d6``).

    Raises:
        KeyError: If a required macro is missing.
    """
    return {
        "repo": Node("repo", f"llama.cpp\n{m['nTagsSampled']} sampled\nreleases", 1.55),
        "s1": Node("step", "1. Build and\nbenchmark each\nrelease once", 2.25),
        "d1": Node("data", f"{m['nRecords']} records\nof {m['nTagsBuilt']} releases", 1.95),
        "s2": Node("step", "2. Detect\nchanges", 1.75),
        "d2": Node("data", f"{m['nCandidates']} + {m['nChangepointEvents']}\ncandidate\nchanges", 1.8),
        "s3": Node("step", "3. Re-measure\nin alternation", 2.1),
        "d3": Node("data", f"{m['nConfirmed']} confirmed\nchanges", 1.8, "RQ1"),
        "s4": Node("step", "4. Bisect to\ncommits", 1.8),
        "d4": Node("data", f"{m['nEventsLocated']} located,\n\u2264 {m['bisectMaxBoundaryCommits']} commits\neach", 1.8,
                   "RQ2"),
        "s5": Node("step", f"5. Check\nvisibility on\nall {m['nSeries']} series", 2.1),
        "d5": Node("data", f"{m['nVisibleCells']} visible\ncells", 1.6, "RQ3"),
        "s6": Node("step", "6. Find the\nsmallest\ncovering set", 1.95),
        "d6": Node("data", f"{m['coverMinSeries']} series\nsee all {m['nConfirmed']}", 1.6, "RQ4"),
    }


def extent(node: Node) -> float:
    """Drawn width of a node (a document stack is wider than its front page)."""
    return node.width + (2 * DOC_DX if node.kind == "data" else 0.0)


def draw_node(ax: plt.Axes, node: Node, left: float, yc: float) -> dict[str, float]:
    """Draw one node with its left edge at ``left`` and its centre line at ``yc``.

    Args:
        ax: Axes in cm coordinates.
        node: The node.
        left: Left edge of the drawn extent.
        yc: Vertical centre (of the front page for a document stack).

    Returns:
        Anchor coordinates: ``left``, ``right``, ``top``, ``bottom`` and ``xc`` (centre of the front part).
    """
    if node.kind == "repo":
        h = 1.3
        gl.cylinder(ax, left, yc - h / 2, node.width, h, node.text, fontsize=LABEL_PT)
        return {"left": left, "right": left + node.width, "top": yc + h / 2, "bottom": yc - h / 2,
                "xc": left + node.width / 2}
    if node.kind == "step":
        gl.rounded_box(ax, left, yc - STEP_H / 2, node.width, STEP_H, node.text, fontsize=LABEL_PT, radius=0.12)
        return {"left": left, "right": left + node.width, "top": yc + STEP_H / 2, "bottom": yc - STEP_H / 2,
                "xc": left + node.width / 2}
    x0 = left + 2 * DOC_DX
    _, bottom, right, top = gl.doc_stack(ax, x0, yc - DOC_H / 2, node.width, DOC_H, node.text, dx=DOC_DX, dy=DOC_DY,
                                         fontsize=LABEL_PT, fc=gl.tint(LIGHT_BLUE, 0.22))
    if node.rq:  # tag on the top-right corner of the stack
        w, h = 0.56, 0.27
        ax.add_patch(FancyBboxPatch((right - w + 0.08, top - h / 2 + 0.02), w, h,
                                    boxstyle="round,pad=0,rounding_size=0.06", fc=INDIGO, ec="white", lw=0.6,
                                    zorder=6))
        ax.text(right - w / 2 + 0.08, top + 0.02, node.rq, ha="center", va="center", fontsize=6.0,
                fontweight="bold", color="white", zorder=7)
    return {"left": left, "right": right, "top": top, "bottom": bottom + 0.04, "xc": x0 + node.width / 2}


def draw_row(ax: plt.Axes, nodes: list[Node], left: float, yc: float) -> list[dict[str, float]]:
    """Draw nodes left to right with arrows between them.

    Args:
        ax: Axes in cm coordinates.
        nodes: Nodes in flow order.
        left: Left edge of the first node.
        yc: Vertical centre of the row.

    Returns:
        Anchors of the nodes, in order.
    """
    anchors = []
    x = left
    for k, node in enumerate(nodes):
        anchors.append(draw_node(ax, node, x, yc))
        if k:
            gl.arrow(ax, (anchors[k - 1]["right"] + 0.04, yc), (anchors[k]["left"] - 0.03, yc))
        x += extent(node) + GAP
    return anchors


def link_label(ax: plt.Axes, x: float, y: float, text: str, ha: str = "center") -> None:
    """Bold label on a connector, on a white ground that interrupts the line."""
    ax.text(x, y, text, ha=ha, va="center", fontsize=LINK_PT, fontweight="bold", color=gl.INK, zorder=5,
            bbox={"fc": "white", "ec": "none", "pad": 1.0})


def draw(nodes: dict[str, Node]) -> plt.Figure:
    """Draw the overview.

    Row 1 runs from the repository to the candidate changes; a connector takes each candidate to
    step 3 in row 2, which continues to the bisection; the visibility and covering-set steps hang
    below the confirmed changes in row 3.

    Args:
        nodes: Nodes from :func:`build_nodes`.

    Returns:
        The figure (axes in cm coordinates).
    """
    fig = plt.figure(figsize=(cm(FULL_WIDTH_CM), cm(HEIGHT_CM)))
    ax = fig.add_axes((0, 0, 1, 1))
    ax.set_xlim(0, FULL_WIDTH_CM)
    ax.set_ylim(0, HEIGHT_CM)
    ax.axis("off")

    row1 = [nodes[k] for k in ("repo", "s1", "d1", "s2", "d2")]
    used = sum(extent(n) for n in row1) + GAP * (len(row1) - 1)
    a1 = draw_row(ax, row1, (FULL_WIDTH_CM - used) / 2, ROW_Y[0])
    a2 = draw_row(ax, [nodes[k] for k in ("s3", "d3", "s4", "d4")], a1[0]["left"], ROW_Y[1])
    s5_left = a2[1]["xc"] - nodes["s5"].width / 2  # step 5 hangs below the confirmed changes
    a3 = draw_row(ax, [nodes[k] for k in ("s5", "d5", "s6", "d6")], s5_left, ROW_Y[2])

    # each candidate change goes to step 3
    y_mid = (a1[-1]["bottom"] + a2[0]["top"]) / 2 + 0.06
    gl.elbow_arrow(ax, [(a1[-1]["xc"], a1[-1]["bottom"]), (a1[-1]["xc"], y_mid), (a2[0]["xc"], y_mid),
                        (a2[0]["xc"], a2[0]["top"] + 0.02)])
    link_label(ax, (a1[-1]["xc"] + a2[0]["xc"]) / 2, y_mid, "For each candidate change")
    # each confirmed change goes to step 5 (and, in row 2, to step 4)
    gl.arrow(ax, (a2[1]["xc"], a2[1]["bottom"]), (a2[1]["xc"], a3[0]["top"] + 0.02))
    link_label(ax, a2[1]["xc"] - 0.12, (a2[1]["bottom"] + a3[0]["top"]) / 2, "For each confirmed change", ha="right")
    return fig


def main() -> None:
    """Read the macros, draw the overview and write PDF and SVG."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    logging.getLogger("fontTools").setLevel(logging.WARNING)
    apply_style()
    fig = draw(build_nodes(read_macros(ROOT / "paper" / "numbers.tex")))
    save_figure(fig, ROOT / "paper" / "figs", "overview")


if __name__ == "__main__":
    main()
