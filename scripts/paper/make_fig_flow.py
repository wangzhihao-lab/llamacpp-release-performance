#!/usr/bin/env python3
"""Generate the two schematic figures of the paper that are not the study overview.

``flow``: what to do with a change seen in a benchmark history, with the counts and costs of this
study on each element.  ``paths``: the code paths of a matrix multiplication in the two back ends with
the confirmed events where they act.

The counts are read from the macros of ``paper/numbers.tex`` (generated by
``scripts/paper/make_numbers.py``), so the figures stay in step with the text.  Nothing under
``paper/`` other than ``paper/figs/`` is written.

Outputs: ``paper/figs/flow`` and ``paper/figs/paths``, each as PDF and SVG (editable text), 13.7 cm wide.

Run: taskpolicy -b nice -n 19 uv run --no-project --with pandas --with numpy --with matplotlib python3 -I scripts/paper/make_fig_flow.py
"""

from __future__ import annotations

import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import glyphs as gl
import matplotlib.pyplot as plt
from figstyle import (
    FULL_WIDTH_CM,
    GREEN,
    INDIGO,
    LIGHT_BLUE,
    ROSE,
    SAND,
    WINE,
    apply_style,
    cm,
    save_figure,
)
from make_fig_overview import read_macros
from matplotlib.patches import FancyBboxPatch, Polygon

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[2]

HEIGHT_CM = 4.12
ROW_TOP, ROW_BOTTOM = 3.04, 0.68  # vertical centres of the two rows
TITLE_PT, NOTE_PT, LINK_PT = 6.9, 6.3, 6.5


def box(ax: plt.Axes, x: float, yc: float, w: float, h: float, title: str, note: str, fc: str = "white") -> None:
    """Rounded box with a bold title and, under it, a note in regular type.

    Args:
        ax: Axes in cm coordinates.
        x: Left edge.
        yc: Vertical centre.
        w: Width.
        h: Height.
        title: Bold text, lines separated by newlines.
        note: Regular text (empty for none).
        fc: Fill colour.
    """
    gl.rounded_box(ax, x, yc - h / 2, w, h, fc=fc, radius=0.1)
    n_title, n_note = title.count("\n") + 1, (note.count("\n") + 1) if note else 0
    line = 0.27
    top = yc + line * (n_title + n_note) / 2
    ax.text(x + w / 2, top - line * n_title / 2, title, ha="center", va="center", fontsize=TITLE_PT, fontweight="bold",
            color=gl.INK, linespacing=1.1, zorder=3)
    if note:
        ax.text(x + w / 2, top - line * (n_title + n_note / 2), note, ha="center", va="center", fontsize=NOTE_PT,
                color=gl.INK, linespacing=1.1, zorder=3)


def diamond(ax: plt.Axes, xc: float, yc: float, w: float, h: float, text: str) -> None:
    """Decision diamond with a centred question."""
    ax.add_patch(Polygon([(xc - w / 2, yc), (xc, yc + h / 2), (xc + w / 2, yc), (xc, yc - h / 2)], closed=True,
                         fc=gl.tint(SAND, 0.45), ec=gl.INK, lw=0.8, joinstyle="round", zorder=2))
    ax.text(xc, yc, text, ha="center", va="center", fontsize=TITLE_PT, fontweight="bold", color=gl.INK, linespacing=1.05,
            zorder=3)


def link(ax: plt.Axes, x: float, y: float, text: str, ha: str = "center") -> None:
    """Bold label beside an arrow."""
    ax.text(x, y, text, ha=ha, va="center", fontsize=LINK_PT, fontweight="bold", color=gl.INK, zorder=5)


def draw(m: dict[str, str]) -> plt.Figure:
    """Draw the flow.

    Args:
        m: Macros from ``numbers.tex``.

    Returns:
        The figure (axes in cm coordinates).

    Raises:
        KeyError: If a required macro is missing.
    """
    refuted = int(m["nNoiseRefuted"]) + int(m["nNoiseRefutedCp"])
    inconclusive = int(m["nNoiseInconclusive"]) + int(m["nNoiseInconclusiveCp"])
    n_switch = 2  # E19 and E46, the two events with a switch control
    n_read = int(m["nConfirmed"]) - n_switch

    fig = plt.figure(figsize=(cm(FULL_WIDTH_CM), cm(HEIGHT_CM)))
    ax = fig.add_axes((0, 0, 1, 1))
    ax.set_xlim(0, FULL_WIDTH_CM)
    ax.set_ylim(0, HEIGHT_CM)
    ax.axis("off")

    h = 1.38
    gap = 0.52  # between neighbours in the top row, so that every arrow keeps a visible shaft
    x_start, w_start = 0.03, 1.85
    x_rem, w_rem = x_start + w_start + gap, 2.95
    w_d1, h_d1 = 1.72, 1.56
    xc_d1 = x_rem + w_rem + gap + w_d1 / 2
    x_bis, w_bis = xc_d1 + w_d1 / 2 + gap, 2.25
    w_d2, h_d2 = 2.7, 1.92
    xc_d2 = x_bis + w_bis + gap + w_d2 / 2
    box(ax, x_start, ROW_TOP, w_start, h, "A change in\na benchmark\nhistory",
        f"{m['nCandidates']} + {m['nChangepointEvents']} events here", gl.tint(LIGHT_BLUE, 0.3))
    box(ax, x_rem, ROW_TOP, w_rem, h, "Re-measure in alternation",
        f"Alternating runs, warm-up,\nA/A run; median {m['remeasureEventMinutes']} min\nof runs per event")
    diamond(ax, xc_d1, ROW_TOP, w_d1, h_d1, "Confirmed\nby the rule?")
    box(ax, x_bis, ROW_TOP, w_bis, h, "Bisect to commits",
        f"{m['nConfirmed']} events,\n{m['bisectBuildsTotal']} builds, median\n{m['bisectBuildSeconds']} s per build")
    diamond(ax, xc_d2, ROW_TOP, w_d2, h_d2, "Can the change\nbe switched off?")

    gl.arrow(ax, (x_start + w_start + 0.04, ROW_TOP), (x_rem - 0.04, ROW_TOP))
    gl.arrow(ax, (x_rem + w_rem + 0.04, ROW_TOP), (xc_d1 - w_d1 / 2 - 0.03, ROW_TOP))
    gl.arrow(ax, (xc_d1 + w_d1 / 2 + 0.03, ROW_TOP), (x_bis - 0.04, ROW_TOP))
    link(ax, (xc_d1 + w_d1 / 2 + x_bis) / 2, ROW_TOP + 0.17, "Yes")
    gl.arrow(ax, (x_bis + w_bis + 0.04, ROW_TOP), (xc_d2 - w_d2 / 2 - 0.03, ROW_TOP))

    # leaves
    leaf_h = 1.24
    leaf_top = ROW_BOTTOM + leaf_h / 2 + 0.01
    w_keep = 3.3
    x_keep = xc_d1 - w_keep / 2 - 0.35
    box(ax, x_keep, ROW_BOTTOM, w_keep, leaf_h, "Not confirmed",
        f"{refuted} refuted, {inconclusive} inconclusive\nhere; state the smallest\nconfirmable change",
        gl.tint(ROSE, 0.2))
    gl.arrow(ax, (xc_d1, ROW_TOP - h_d1 / 2 - 0.01), (xc_d1, leaf_top))
    link(ax, xc_d1 + 0.08, (ROW_TOP - h_d1 / 2 + leaf_top) / 2, "No", ha="left")

    w_read = 2.35
    x_read = x_keep + w_keep + 0.25
    box(ax, x_read, ROW_BOTTOM, w_read, leaf_h, "Read the diff and\nthe pull request", f"{n_read} events here",
        gl.tint(GREEN, 0.14))
    w_sw = 2.55
    x_sw = xc_d2 - w_sw / 2
    box(ax, x_sw, ROW_BOTTOM, w_sw, leaf_h, "Test the mechanism\nwith a switch control", f"{n_switch} events here",
        gl.tint(GREEN, 0.14))
    # the "no" branch leaves the diamond below the level of the bisection box
    y_no = ROW_TOP - 0.74
    x_edge = xc_d2 - (w_d2 / 2) * (1 - 0.74 / (h_d2 / 2))
    x_leaf = x_read + w_read / 2
    gl.elbow_arrow(ax, [(x_edge, y_no), (x_leaf, y_no), (x_leaf, leaf_top)])
    link(ax, x_leaf + 0.08, (y_no + leaf_top) / 2, "No", ha="left")
    gl.arrow(ax, (xc_d2, ROW_TOP - h_d2 / 2 - 0.01), (xc_d2, leaf_top))
    link(ax, xc_d2 + 0.08, (ROW_TOP - h_d2 / 2 + leaf_top) / 2, "Yes", ha="left")
    return fig


PATHS_HEIGHT_CM = 3.3
REGRESSIONS = ("E03", "E19", "E46")  # the events that lower throughput, checked against the macros in main()


def tag(ax: plt.Axes, x_right: float, y: float, events: tuple[str, ...]) -> None:
    """Row of event tags ending at ``x_right``: regressions in indigo, improvements in wine."""
    w, h, gap = 0.5, 0.25, 0.04
    x = x_right
    for event in reversed(events):
        x -= w
        ax.add_patch(FancyBboxPatch((x, y - h / 2), w, h, boxstyle="round,pad=0,rounding_size=0.05",
                                    fc=INDIGO if event in REGRESSIONS else WINE, ec="white", lw=0.5, zorder=6))
        ax.text(x + w / 2, y - 0.005, event, ha="center", va="center", fontsize=5.8, fontweight="bold", color="white",
                zorder=7)
        x -= gap


def step(ax: plt.Axes, x: float, yc: float, w: float, h: float, title: str, note: str = "",
         events: tuple[str, ...] = (), fc: str = "white") -> None:
    """Box of the paths figure with event tags on its top edge."""
    box(ax, x, yc, w, h, title, note, fc)
    if events:
        tag(ax, x + w - 0.06, yc + h / 2 + 0.04, events)


def draw_paths() -> plt.Figure:
    """Draw the code paths of the two back ends with the confirmed events.

    Returns:
        The figure (axes in cm coordinates).
    """
    width, height = FULL_WIDTH_CM, PATHS_HEIGHT_CM
    fig = plt.figure(figsize=(cm(width), cm(height)))
    ax = fig.add_axes((0, 0, 1, 1))
    ax.set_xlim(0, width)
    ax.set_ylim(0, height)
    ax.axis("off")
    top, mid, low = 2.55, 1.28, 0.27
    h = 0.74
    prompt_fc, token_fc = gl.tint(LIGHT_BLUE, 0.3), "0.95"

    ax.text(0.03, height - 0.13, "Metal back end", ha="left", va="center", fontsize=7.2, fontweight="bold", color=gl.INK)
    step(ax, 0.03, top, 2.9, h, "Start-up probes", "set has tensor", ("E49",))
    step(ax, 3.45, top, 2.9, h, "Per multiplication:", "choice of kernel", ("E01",))
    gl.arrow(ax, (2.96, top), (3.42, top))
    step(ax, 0.03, mid, 3.0, h, "Matrix-matrix kernels", "tensor API if has tensor", ("E01", "E50"), prompt_fc)
    step(ax, 3.45, mid, 2.9, h, "Matrix-vector kernels", "", ("E01",), token_fc)
    gl.elbow_arrow(ax, [(3.75, top - h / 2), (3.75, top - h / 2 - 0.2), (1.53, top - h / 2 - 0.2), (1.53, mid + h / 2 + 0.02)])
    gl.arrow(ax, (4.9, top - h / 2), (4.9, mid + h / 2 + 0.02))

    x0 = 6.95
    ax.text(x0, height - 0.13, "CPU back end", ha="left", va="center", fontsize=7.2, fontweight="bold", color=gl.INK)
    step(ax, x0, top, 3.15, h, "Loading the weights:", "repack for the CPU kernels", ("E46",))
    step(ax, x0 + 3.55, top, 3.15, h, "Per multiplication:", "hand over to BLAS?", ("E03", "E04"))
    gl.arrow(ax, (x0 + 3.18, top), (x0 + 3.52, top))
    step(ax, x0, mid, 3.15, h, "BLAS back end", "weights converted to floats", ("E16",), prompt_fc)
    step(ax, x0 + 3.55, mid, 3.15, h, "GGML CPU kernels", "plain or repacked", (), token_fc)
    gl.elbow_arrow(ax, [(x0 + 3.85, top - h / 2), (x0 + 3.85, top - h / 2 - 0.2), (x0 + 1.57, top - h / 2 - 0.2),
                        (x0 + 1.57, mid + h / 2 + 0.02)])
    gl.arrow(ax, (x0 + 5.12, top - h / 2), (x0 + 5.12, mid + h / 2 + 0.02))
    step(ax, x0, low, 6.7, 0.44, "Thread pool around the CPU work: idle threads poll", "", ("E19",))

    # legend: the event tags beside the heading, the shading of the paths below the Metal back end
    yl = height - 0.13
    for x, color, text in ((3.45, INDIGO, "Regression"), (4.95, WINE, "Gain")):
        ax.add_patch(FancyBboxPatch((x, yl - 0.09), 0.3, 0.18, boxstyle="round,pad=0,rounding_size=0.03", fc=color, ec="none"))
        ax.text(x + 0.36, yl, text, ha="left", va="center", fontsize=6.5, color=gl.INK)
    for x, fc, text in ((0.03, prompt_fc, "Mainly prompt processing"), (3.45, token_fc, "Mainly token generation")):
        ax.add_patch(FancyBboxPatch((x, low - 0.09), 0.3, 0.18, boxstyle="round,pad=0,rounding_size=0.03", fc=fc, ec=gl.INK, lw=0.6))
        ax.text(x + 0.38, low, text, ha="left", va="center", fontsize=6.5, color=gl.INK)
    return fig


def main() -> None:
    """Read the macros, draw both figures and write PDF and SVG."""
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    logging.getLogger("fontTools").setLevel(logging.WARNING)
    apply_style()
    macros = read_macros(ROOT / "paper" / "numbers.tex")
    if int(macros["nRegressions"]) != len(REGRESSIONS):
        raise ValueError(f"REGRESSIONS {REGRESSIONS} do not match nRegressions = {macros['nRegressions']}")
    save_figure(draw(macros), ROOT / "paper" / "figs", "flow")
    save_figure(draw_paths(), ROOT / "paper" / "figs", "paths")


if __name__ == "__main__":
    main()
